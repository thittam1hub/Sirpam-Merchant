/// One-page end-of-day accounting summary.
///
/// The vendor's accountant wants a single sheet per trading day: what was
/// sold, how it was tendered, what was discounted or taxed, what went out as
/// costs, and whether the cash box matched. Everything here comes from the
/// saved [DayClose] snapshot so a later menu or price edit cannot rewrite a
/// day that has already been closed.
library;

import 'dart:typed_data';

import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../../core/settings/settings_controller.dart';
import '../domain/expense.dart';

String _money(int paise) =>
    NumberFormat.currency(locale: 'en_IN', symbol: 'Rs ', decimalDigits: 2)
        .format(paise / 100);

Future<Uint8List> buildDayClosePdf(DayClose close, VendorSettings s) async {
  final doc = pw.Document(
    title: 'VendorOS Day Close ${close.day}',
    author: s.stallName.isEmpty ? 'VendorOS' : s.stallName,
  );
  const ink = PdfColor.fromInt(0xFF1A2233);
  const rule = PdfColor.fromInt(0xFFBAC5D5);

  pw.Widget row(String k, String v, {bool bold = false}) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 3),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(k, style: const pw.TextStyle(fontSize: 10, color: ink)),
            pw.Text(v,
                style: pw.TextStyle(
                    fontSize: 10,
                    color: ink,
                    fontWeight:
                        bold ? pw.FontWeight.bold : pw.FontWeight.normal)),
          ],
        ),
      );

  pw.Widget heading(String t) => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 14, bottom: 4),
        child: pw.Text(t.toUpperCase(),
            style: pw.TextStyle(
                fontSize: 9, letterSpacing: 1.1, fontWeight: pw.FontWeight.bold)),
      );

  final diff = close.differencePaise;

  doc.addPage(
    pw.Page(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(36),
      build: (_) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.stretch,
        children: [
          pw.Text(s.stallName.isEmpty ? 'VendorOS' : s.stallName,
              style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold)),
          pw.Text('Day close statement - ${close.day}',
              style: const pw.TextStyle(fontSize: 11, color: ink)),
          pw.Divider(color: rule),
          heading('Orders'),
          row('Orders taken', '${close.ordersTaken}'),
          row('Orders cancelled', '${close.ordersCancelled}'),
          row('Last token issued', '${close.lastToken}'),
          heading('Billing'),
          row('Billed value', _money(close.billedPaise)),
          row('Discounts given', '- ${_money(close.discountPaise)}'),
          row('Tax collected', _money(close.taxPaise)),
          heading('Tenders'),
          row('UPI', _money(close.upiPaise)),
          row('Credit (udhaar)', _money(close.creditPaise)),
          row('Expenses paid out', '- ${_money(close.expensePaise)}'),
          pw.Divider(color: rule),
          row('Expected in cash box', _money(close.expectedCashPaise),
              bold: true),
          row('Counted in cash box', _money(close.countedCashPaise), bold: true),
          row(
              diff == 0
                  ? 'Cash matched'
                  : diff > 0
                      ? 'Surplus'
                      : 'Shortage',
              _money(diff.abs()),
              bold: true),
          pw.Spacer(),
          pw.Text(
              'Closed on ${DateFormat('dd MMM yyyy, h:mm a').format(DateTime.fromMillisecondsSinceEpoch(close.ts))}. '
              'Self-declared record generated by VendorOS from the vendor\'s own daily entries.',
              style: const pw.TextStyle(fontSize: 7)),
        ],
      ),
    ),
  );
  return doc.save();
}
